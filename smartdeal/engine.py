"""Deterministic, transparent shopping result normalization and scoring."""
from __future__ import annotations
from dataclasses import dataclass, asdict
from datetime import datetime, timezone
import math
import re
from urllib.parse import urlparse

STOPWORDS = {"the", "a", "an", "of", "for", "with", "and", "in", "to", "by", "on", "new", "sale", "best", "buy", "under", "cheap", "deal", "deals", "at", "from"}

@dataclass
class Offer:
    title: str
    merchant: str
    price: float
    url: str
    rating: float | None = None
    reviews: int | None = None
    old_price: float | None = None
    shipping: float | None = None
    shipping_note: str = "Shipping not verified"
    image: str = ""
    product_id: str = ""
    condition: str = "new / unspecified"
    checked_at: str = ""
    source: str = "SerpApi Google Shopping"
    match_score: float = 0
    value_score: float = 0

    def serialize(self) -> dict:
        return asdict(self)

    @property
    def known_total(self) -> float:
        return round(self.price + (self.shipping or 0), 2)

    @property
    def discount_pct(self) -> float | None:
        if not self.old_price or self.old_price <= self.price:
            return None
        return round(100 * (self.old_price - self.price) / self.old_price, 1)


def numeric(value):
    try:
        if value is None or isinstance(value, bool):
            return None
        if isinstance(value, str):
            value = re.sub(r"[^0-9.\-]", "", value)
        result = float(value)
        return result if math.isfinite(result) and result >= 0 else None
    except (ValueError, TypeError):
        return None


def tokens(text: str) -> set[str]:
    return {t for t in re.findall(r"[a-z0-9]+", text.lower()) if t not in STOPWORDS and len(t)>1}


def relevance(query: str, title: str) -> float:
    q = tokens(query)
    if not q:
        return 0
    t = tokens(title)
    return round(len(q & t) / len(q), 3)


def valid_url(url: str) -> bool:
    try:
        parsed = urlparse(url)
        return parsed.scheme == "https" and bool(parsed.hostname) and not parsed.username
    except ValueError:
        return False


def parse_shipping(text: str | None) -> tuple[float | None, str]:
    """Only treat a plainly stated free shipping or numeric delivery fee as known."""
    if not text:
        return None, "Shipping not verified"
    t = str(text).strip()
    if re.search(r"\bfree\s+(?:delivery|shipping)\b", t, re.I):
        return 0., t
    if re.fullmatch(r"\$\s*\d+(?:\.\d{1,2})?\s+(?:delivery|shipping)", t, re.I):
        return numeric(t.split()[0]), t
    return None, t


def normalize_item(raw: dict, checked_at: str | None = None) -> Offer | None:
    """Google Shopping result may contain product_link or link, often Google URL.
    Do not present the Google result as a direct merchant checkout link.
    """
    price = numeric(raw.get("extracted_price"))
    if price is None or price <= 0 or raw.get("installment"):
        return None
    link = raw.get("product_link") or raw.get("link") or ""
    if not valid_url(link):
        return None
    rating = numeric(raw.get("rating"))
    if rating is not None and not 0 <= rating <= 5:
        rating = None
    reviews = numeric(raw.get("reviews"))
    shipping, note = parse_shipping(raw.get("delivery"))
    old_price = numeric(raw.get("extracted_old_price"))
    return Offer(
        title=str(raw.get("title") or "Untitled product")[:300],
        merchant=str(raw.get("source") or "Merchant unspecified")[:100],
        price=round(price, 2), url=link,
        rating=rating, reviews=int(reviews) if reviews is not None else None,
        old_price=old_price, shipping=shipping, shipping_note=note,
        image=raw.get("thumbnail") or "", product_id=str(raw.get("product_id") or ""),
        condition=str(raw.get("second_hand_condition") or "new / unspecified"),
        checked_at=checked_at or datetime.now(timezone.utc).isoformat(),
    )


def score_offers(offers: list[Offer], query: str, budget: float | None = None,
                 min_rating: float = 0, strict_relevance: bool = True) -> list[Offer]:
    """Ranking is calculated in Python, not generated by an LLM.
    No implied comparability of different products; matching remains approximate.
    Missing review data is penalized (not fabricated).
    """
    results = []
    for offer in offers:
        offer.match_score = relevance(query, offer.title)
        if strict_relevance and offer.match_score < 0.33:
            continue
        if budget is not None and offer.price > budget:
            continue
        if min_rating and (offer.rating is None or offer.rating < min_rating):
            continue
        results.append(offer)
    if not results:
        return []
    lowest = min(x.price for x in results)
    for x in results:
        price_component = 100 * lowest / x.price
        rating_component = 100 * (x.rating / 5) if x.rating is not None else 40
        review_component = 100 * min(1, math.log1p(x.reviews or 0) / math.log1p(1000))
        x.value_score = round(.45*price_component + .30*rating_component + .15*review_component + .10*(x.match_score*100), 1)
    return sorted(results, key=lambda x: (-x.value_score, x.price))


def exact_product_groups(offers: list[Offer]) -> dict[str,list[Offer]]:
    """Only group same product when Google product_id matches. No guesswork via title."""
    groups: dict[str, list[Offer]] = {}
    for o in offers:
        if o.product_id:
            groups.setdefault(o.product_id, []).append(o)
    return {k:v for k,v in groups.items() if len({o.merchant.lower() for o in v}) > 1}
